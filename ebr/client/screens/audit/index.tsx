import { type FormEvent, useEffect, useState } from 'react';
import { api } from '../../api.js';
import { errorText, formatWhen, useI18n } from '../../i18n/index.js';
import { Alert, Button, Card, TextField } from '../../ui/index.js';
import type { Screen } from '../registry.js';

type Entry = { id: string; at: string; actorName: string; action: string; entity: string; entityId: string; oldValue: unknown; newValue: unknown; reason: string | null };
type Sig = { id: string; meaning: string; signerName: string; signedAt: string; recordVersion: number; comment: string | null; valid?: boolean };
type Me = { permissions: string[] };
const show = (v: unknown) => (v === null || v === undefined ? '' : typeof v === 'string' ? v : JSON.stringify(v));

/** The history of one record, oldest first, with its signatures (E32#3). */
function RecordHistory({ entity, entityId, onClose }: { entity: string; entityId: string; onClose: () => void }) {
  const { t, lang } = useI18n();
  const [h, setH] = useState<{ entries: Entry[]; sigs: Sig[] } | null>(null);
  const [error, setError] = useState<string | null>(null);
  useEffect(() => {
    const q = `entity=${encodeURIComponent(entity)}&entityId=${encodeURIComponent(entityId)}`;
    void Promise.all([api<Entry[]>('GET', `/api/audit?${q}`), api<Sig[]>('GET', `/api/signatures?${q}`)]).then(([entries, sigs]) => setH({ entries, sigs })).catch(e => setError(errorText(t, e, 'Not loaded.')));
  }, [entity, entityId]);
  return (
    <Card title={t('History of {entity} {id}', { entity, id: entityId })}>
      <div className="mb-2"><Button variant="secondary" onClick={onClose}>{t('Close')}</Button></div>
      {error ? <Alert>{error}</Alert> : !h ? <p role="status">{t('Loading…')}</p> : <>
        <h3 className="text-base font-bold">{t('Signatures')}</h3>
        {h.sigs.length === 0 ? <p className="text-base">{t('No signature on this record.')}</p> : <ul className="mb-3 flex flex-col gap-1">{h.sigs.map(s => (
          <li key={s.id} className="text-base">{formatWhen(lang, s.signedAt)} · {s.signerName} · {t(`meaning.${s.meaning}`)} · {t('record version {n}', { n: s.recordVersion })}{s.comment ? ` · ${s.comment}` : ''}</li>))}</ul>}
        <h3 className="text-base font-bold">{t('Audit trail')}</h3>
        <ol className="flex flex-col gap-2">{h.entries.map(e => (
          <li key={e.id} className="rounded-lg border border-slate-200 p-2 text-sm">
            <p className="text-base"><b dir="ltr">{e.action}</b> · {formatWhen(lang, e.at)} · {e.actorName}</p>
            {e.reason ? <p>{t('Reason: {text}', { text: e.reason })}</p> : null}
            {e.oldValue !== null && e.oldValue !== undefined ? <p className="break-all" dir="ltr">{t('Before')}: {show(e.oldValue)}</p> : null}
            {e.newValue !== null && e.newValue !== undefined ? <p className="break-all" dir="ltr">{t('After')}: {show(e.newValue)}</p> : null}
          </li>))}</ol>
      </>}
    </Card>
  );
}

/** E32#3: QA checks a PDF it was given: is it a certified copy this system registered, unchanged? */
function CopyCheck() {
  const { t, lang } = useI18n();
  const [r, setR] = useState<{ genuine: boolean; batchNumber?: string; generatedBy?: string; generatedAt?: string; sha256: string } | null>(null);
  const [error, setError] = useState<string | null>(null);
  async function check(e: FormEvent<HTMLFormElement>) {
    e.preventDefault();
    const file = new FormData(e.currentTarget).get('pdf');
    if (!(file instanceof File) || !file.size) return;
    const bytes = new Uint8Array(await file.arrayBuffer());
    let bin = ''; for (let i = 0; i < bytes.length; i += 0x8000) bin += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
    try { setR(await api('POST', '/api/certified-copies/verify', { pdfBase64: btoa(bin) })); setError(null); } catch (err) { setR(null); setError(errorText(t, err, 'Not done.')); }
  }
  return (
    <Card title={t('Check a certified copy')}>
      <form onSubmit={check} className="flex flex-col gap-2" aria-label={t('Check a certified copy')}>
        <div className="flex flex-col gap-1"><label htmlFor="copy-pdf" className="text-sm font-semibold text-slate-700">{t('PDF file *')}</label>
          <input id="copy-pdf" name="pdf" type="file" accept="application/pdf" required className="min-h-11 text-base" /></div>
        <div><Button type="submit">{t('Check')}</Button></div>
      </form>
      {r ? (r.genuine
        ? <Alert kind="info">{t('Genuine: the certified copy of batch {batch}, generated by {name}, {when}.', { batch: r.batchNumber, name: r.generatedBy, when: formatWhen(lang, r.generatedAt!) })}</Alert>
        : <Alert>{t('Not genuine: this file is not a certified copy registered by this system, or it was changed.')}</Alert>) : null}
      {error ? <Alert>{error}</Alert> : null}
    </Card>
  );
}

function Audit() {
  const { t, lang } = useI18n();
  const [me, setMe] = useState<Me | null>(null);
  const [list, setList] = useState<Entry[] | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [chain, setChain] = useState<{ ok: boolean; entries: number; brokenAt?: string; why?: string } | null>(null);
  const [record, setRecord] = useState<{ entity: string; entityId: string } | null>(null);
  const search = (q = '') => void api<Entry[]>('GET', `/api/audit/recent${q}`).then(l => { setList(l); setError(null); }).catch(e => setError(errorText(t, e, 'Not loaded.')));
  useEffect(() => { search(); void api<Me>('GET', '/api/auth/me').then(setMe); }, []);
  function filter(e: FormEvent<HTMLFormElement>) {
    e.preventDefault();
    const f = new FormData(e.currentTarget), q = new URLSearchParams();
    for (const k of ['entity', 'entityId', 'action', 'actor', 'from', 'to']) { const v = String(f.get(k) ?? '').trim(); if (v) q.set(k, v); }
    search(q.size ? `?${q}` : '');
  }
  if (!me) return <p role="status">{t('Loading…')}</p>;
  return (
    <div className="flex flex-col gap-4">
      {me.permissions.includes('audit.verify') ? <Card title={t('Integrity of the audit trail')}>
        <p className="mb-2 text-base">{t('Every entry carries the hash of the one before: a changed or deleted entry breaks the chain.')}</p>
        <Button onClick={() => void api<typeof chain>('GET', '/api/audit/verify').then(setChain).catch(e => setError(errorText(t, e, 'Not done.')))}>{t('Verify the chain')}</Button>
        {chain ? <div className="mt-2">{chain.ok ? <Alert kind="info">{t('The chain is intact: {n} entries checked.', { n: chain.entries })}</Alert> : <Alert>{t('The chain is BROKEN at entry {id}: {why}', { id: chain.brokenAt, why: chain.why })}</Alert>}</div> : null}
      </Card> : null}
      {record ? <RecordHistory {...record} onClose={() => setRecord(null)} /> : null}
      <Card title={t('Audit trail review')}>
        <form onSubmit={filter} className="mb-3 grid gap-2 md:grid-cols-3" aria-label={t('Filter the audit trail')}>
          <TextField label={t('Record type')} name="entity" dir="ltr" hint={t('For example batch, logbook, mbr, user, site_setting')} />
          <TextField label={t('Record id')} name="entityId" dir="ltr" />
          <TextField label={t('Action')} name="action" dir="ltr" hint={t('For example batch. or auth.failed')} />
          <TextField label={t('User')} name="actor" dir="ltr" />
          <TextField label={t('From')} name="from" type="date" />
          <TextField label={t('To')} name="to" type="date" />
          <div className="md:col-span-3"><Button type="submit">{t('Show')}</Button></div>
        </form>
        {error ? <Alert>{error}</Alert> : null}
        {!list ? <p role="status">{t('Loading…')}</p> : list.length === 0 ? <p className="text-base">{t('No entry matches.')}</p> : (
          <ul className="flex flex-col gap-2" aria-label={t('Audit entries')}>{list.map(e => (
            <li key={e.id} className="flex flex-col gap-1 rounded-lg border border-slate-200 p-2">
              <p className="text-base"><b dir="ltr">{e.action}</b> · {formatWhen(lang, e.at)} · {e.actorName}{e.reason ? ` · ${e.reason}` : ''}</p>
              <div><Button variant="secondary" onClick={() => setRecord({ entity: e.entity, entityId: e.entityId })}>{t('History of {entity} {id}', { entity: e.entity, id: e.entityId.slice(0, 12) })}</Button></div>
            </li>))}</ul>)}
      </Card>
      <CopyCheck />
    </div>
  );
}
export const screen: Screen = { id: 'audit', title: 'Audit trail', order: 80, permission: 'audit.read', Component: Audit };
