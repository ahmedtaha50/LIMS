-- ---- guards (structure, not constants: restored with the schema) ---------------------------------------------------------------

-- A Completed review is evidence: it cannot be edited, and no review is ever deleted.
CREATE FUNCTION periodic_reviews_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
	IF TG_OP = 'DELETE' THEN
		RAISE EXCEPTION 'periodic_reviews is append-only: a review cannot be deleted' USING ERRCODE = 'P0423';
	END IF;
	IF OLD.status IN ('Completed', 'Cancelled') THEN
		RAISE EXCEPTION 'a % periodic review cannot be changed', OLD.status USING ERRCODE = 'P0423';
	END IF;
	IF NEW.evidence IS DISTINCT FROM OLD.evidence OR NEW.evidence_sha256 IS DISTINCT FROM OLD.evidence_sha256 THEN
		RAISE EXCEPTION 'the evidence of a periodic review is fixed when it is opened' USING ERRCODE = 'P0423';
	END IF;
	RETURN NEW;
END $$;
CREATE TRIGGER periodic_reviews_guard BEFORE UPDATE OR DELETE ON "periodic_reviews" FOR EACH ROW EXECUTE FUNCTION periodic_reviews_guard();

-- The archive sidecar and the register of holds, flags and bundles are never deleted; archived_records is also never updated.
CREATE FUNCTION archive_tables_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
	IF TG_OP = 'DELETE' OR TG_TABLE_NAME = 'archived_records' THEN
		RAISE EXCEPTION '% is append-only', TG_TABLE_NAME USING ERRCODE = 'P0423';
	END IF;
	RETURN NEW;
END $$;
CREATE TRIGGER archived_records_guard BEFORE UPDATE OR DELETE ON "archived_records" FOR EACH ROW EXECUTE FUNCTION archive_tables_guard();
CREATE TRIGGER archive_bundles_guard BEFORE DELETE ON "archive_bundles" FOR EACH ROW EXECUTE FUNCTION archive_tables_guard();
CREATE TRIGGER legal_holds_guard BEFORE DELETE ON "legal_holds" FOR EACH ROW EXECUTE FUNCTION archive_tables_guard();
CREATE TRIGGER retention_flags_guard BEFORE DELETE ON "retention_flags" FOR EACH ROW EXECUTE FUNCTION archive_tables_guard();

-- A record class (or the record) under an Active legal hold cannot be flagged for purge, and only an archived record can be flagged.
-- This holds for every path, not only the API. (A foreign key to archived_records would say the same, but drizzle-kit's introspection used by
-- the schema-drift check cannot read a foreign key onto a composite unique index.)
CREATE FUNCTION retention_flags_hold_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
	IF TG_OP = 'INSERT' AND NOT EXISTS (SELECT 1 FROM archived_records a WHERE a.entity_type = NEW.entity_type AND a.entity_id = NEW.entity_id) THEN
		RAISE EXCEPTION '% % is not archived: only an archived record can be flagged', NEW.entity_type, NEW.entity_id USING ERRCODE = 'P0423';
	END IF;
	IF NEW.status = 'Flagged' AND EXISTS (
		SELECT 1 FROM legal_holds h WHERE h.status = 'Active' AND h.record_class = NEW.record_class AND (h.scope_ref IS NULL OR h.scope_ref = NEW.entity_id)
	) THEN
		RAISE EXCEPTION 'record class % is under legal hold: it cannot be flagged for purge', NEW.record_class USING ERRCODE = 'P0423';
	END IF;
	RETURN NEW;
END $$;
CREATE TRIGGER retention_flags_hold_guard BEFORE INSERT OR UPDATE ON "retention_flags" FOR EACH ROW EXECUTE FUNCTION retention_flags_hold_guard();

-- An archived record is read-only (roadmap M42): the key of the record is its id, the type is the trigger argument.
CREATE FUNCTION archived_record_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
	IF EXISTS (SELECT 1 FROM archived_records a WHERE a.entity_type = TG_ARGV[0] AND a.entity_id = OLD.id) THEN
		RAISE EXCEPTION '% % is archived and read-only', TG_ARGV[0], OLD.id USING ERRCODE = 'P0423';
	END IF;
	IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
	RETURN NEW;
END $$;
CREATE TRIGGER samples_archived_guard BEFORE UPDATE OR DELETE ON "samples" FOR EACH ROW EXECUTE FUNCTION archived_record_guard('Sample');
CREATE TRIGGER results_archived_guard BEFORE UPDATE OR DELETE ON "results" FOR EACH ROW EXECUTE FUNCTION archived_record_guard('Result');
CREATE TRIGGER product_batches_archived_guard BEFORE UPDATE OR DELETE ON "product_batches" FOR EACH ROW EXECUTE FUNCTION archived_record_guard('ProductBatch');
CREATE TRIGGER batch_releases_archived_guard BEFORE UPDATE OR DELETE ON "batch_releases" FOR EACH ROW EXECUTE FUNCTION archived_record_guard('BatchRelease');
CREATE TRIGGER coa_documents_archived_guard BEFORE UPDATE OR DELETE ON "coa_documents" FOR EACH ROW EXECUTE FUNCTION archived_record_guard('CoaDocument');

