-- 0330_periodic_archive: periodic review, retention policies and legal hold, and verifiable batch archives
-- (roadmap M42, r3-periodic-archive; EU GMP Annex 11 sections 11 and 17, 21 CFR 211.180, 21 CFR Part 11.10(c)).
--
-- What this adds, and why:
--   periodic_review_plans   what is reviewed, how often and when it is next due: one Active plan per (kind, subject). Kinds: user_access,
--                           instrument, specification, method, document, module, system. The checklist is the plan's template.
--   periodic_reviews        one review of one plan for one due date: Open -> Completed (QA e-signature PERIODIC_REVIEW) or Cancelled. The
--                           evidence (a JSON snapshot of the records reviewed, with its SHA-256) is generated by the server when the review is
--                           opened and never edited; findings and the conclusion are recorded by the reviewer. A Completed review cannot be
--                           changed or deleted (trigger).
--   retention_policies      per record class, the number of years to keep. No row, or retention_years NULL, means keep indefinitely: the
--                           conservative default. The number is a decision of the organisation (QA e-signature RETENTION_POLICY).
--   legal_holds             a hold on a record class (or on one record of it). While one is Active, nothing of that class can be flagged
--                           for purge (retention_flags trigger). Placing and releasing are e-signed (LEGAL_HOLD).
--   retention_flags         "this archived record has outlived its retention and may be considered for disposal". It is ONLY a flag: the
--                           application ships no purge function and nothing here deletes a GxP record.
--   archive_bundles         the register of export bundles (a folder of open-format files with a SHA-256 manifest). Built -> Archived by a
--                           QA e-signature (ARCHIVE_DECISION) that is bound to the manifest hash.
--   archived_records        the sidecar that marks records as archived: written once, in the transaction of the QA decision, never changed.
--                           The core tables are not altered; triggers refuse an UPDATE or DELETE of an archived sample, result, batch,
--                           batch release or CoA (the HTTP guard answers 423 first; the trigger is the backstop for every other path).
--   signature_meanings      + PERIODIC_REVIEW, ARCHIVE_DECISION, RETENTION_POLICY, LEGAL_HOLD (QA only).
--   permissions             + periodic.view, periodic.manage, periodic.sign, archive.view, archive.manage, retention.manage (330-335).
--
-- The constants are written only under the migration runner (WHERE EXISTS schema_migrations), because a restore replays this file into an
-- EMPTY database.

CREATE TABLE "periodic_review_plans" (
	"id" text PRIMARY KEY NOT NULL,
	"kind" text NOT NULL,
	"subject_id" text NOT NULL,
	"title" text NOT NULL,
	"interval_months" integer NOT NULL,
	"next_due_date" text NOT NULL,
	"checklist" jsonb DEFAULT '[]'::jsonb NOT NULL,
	"status" text DEFAULT 'Active' NOT NULL,
	"created_by" text NOT NULL,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	"version" integer DEFAULT 1 NOT NULL,
	CONSTRAINT "periodic_review_plans_kind_check" CHECK ("periodic_review_plans"."kind" IN ('user_access', 'instrument', 'specification', 'method', 'document', 'module', 'system')),
	CONSTRAINT "periodic_review_plans_status_check" CHECK ("periodic_review_plans"."status" IN ('Active', 'Retired')),
	CONSTRAINT "periodic_review_plans_interval_check" CHECK ("periodic_review_plans"."interval_months" BETWEEN 1 AND 120),
	CONSTRAINT "periodic_review_plans_due_check" CHECK ("periodic_review_plans"."next_due_date" ~ '^\d{4}-\d{2}-\d{2}$')
);

