import { JOURNAL_DDL, type MigrationFile } from '../migrate';

/**
 * The schema of a given version as one SQL script: the journal table plus the migration files up to `upTo`, in order. It creates
 * structure only (the counters seed is empty on an empty database) and writes no journal or audit rows, so it is what a
 * restore needs: create an empty database at the backup's schema version, then load the backup's rows, which include the journal.
 * desktop/schema.sql is this script for the newest version; `npx tsx src/server/boot/migrate-cli.ts export-schema` rewrites it
 * and tests/upgrade/desktop-schema.test.ts fails when it is stale.
 */
export function buildSchemaSql(files: MigrationFile[], upTo?: string): string {
  const parts = upTo ? files.filter(f => f.id <= upTo) : files;
  return [
    '-- GENERATED by `npx tsx src/server/boot/migrate-cli.ts export-schema` from drizzle/*.sql. Do not edit; add a migration instead.',
    '-- Structure of the current schema for restoring a backup into an empty database. Installs and upgrades run the migrations',
    '-- (src/server/migrate.ts), not this file.',
    '',
    `${JOURNAL_DDL};`,
    ...parts.flatMap(f => ['', `-- ===== ${f.id} (sha256 ${f.sha256}) =====`, f.sql.trimEnd()]),
    '',
  ].join('\n');
}
